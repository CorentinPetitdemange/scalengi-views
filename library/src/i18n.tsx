interface I18nValue {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  t: (text: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);
const dictionaries: Partial<Record<AppLocale, Record<string, string>>> = { en: english };
const isAppLocale = (value: string | null): value is AppLocale => APP_LOCALES.some((locale) => locale.code === value);

export function translate(locale: AppLocale, text: string) {
  return dictionaries[locale]?.[text] ?? text;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>("en");

  useEffect(() => {
    const timer = window.setTimeout(() => {
      const saved = localStorage.getItem(LOCALE_KEY);
      setLocaleState(isAppLocale(saved) ? saved : "en");
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);

  const setLocale = useCallback((next: AppLocale) => {
    setLocaleState(next);
    localStorage.setItem(LOCALE_KEY, next);
  }, []);
  const t = useCallback((text: string) => translate(locale, text), [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  useEffect(() => { document.documentElement.lang = locale; }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider.");
  return value;
}
